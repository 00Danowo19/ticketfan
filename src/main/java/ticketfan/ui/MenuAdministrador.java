    private void guardarCambiosEvento() {
        if (idEventoModificar == null) { JOptionPane.showMessageDialog(this, "Selecciona un evento desde la tabla."); return; }
        String nombre = JtxtModificarNombreEvento.getText().trim();
        int tipo = idSeleccionado(JcbxModificarTipoEvento, tiposModificar);
        int cuenta = idSeleccionado(JcbxModificarCuentaReceptora, cuentasModificar);
        int edad = ((Number) JspnModificarEdadMinima.getValue()).intValue();
        int cantidad = ((Number) JspnModificarCantidadBoletos.getValue()).intValue();
        BigDecimal precio = BigDecimal.valueOf(((Number) JspnModificarPrecioBoleto.getValue()).doubleValue());
        if (nombre.isEmpty() || tipo == 0 || cuenta == 0 || cantidad < 1 || precio.compareTo(BigDecimal.ZERO) <= 0) {
            JOptionPane.showMessageDialog(this, "Revisa los datos del evento."); return;
        }
        try {
            dao.modificarEvento(new EventData(idEventoModificar, idPromotoraObjetivo, tipo, cuenta, nombre, edad,
                    JtxtModificarImagenEvento.getText().trim(), cantidad, precio));
            JOptionPane.showMessageDialog(this, "Evento modificado correctamente.");
            cargarEventosAdmin(); mostrarCard("card2");
        } catch (Exception ex) { mostrarError("No se pudo modificar el evento", ex); }
    }


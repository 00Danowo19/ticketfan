    private boolean listo() {
        if (dao == null || session == null) {
            JOptionPane.showMessageDialog(this, "Abre esta pantalla iniciando sesión desde TicketFan.");
            return false;
        }
        return true;
    }

    private void mostrarCard(String card) {
        ((CardLayout) JpnContenidoCliente.getLayout()).show(JpnContenidoCliente, card);
    }

    private void cargarTabla(JTable tabla, List<Object[]> filas) {
        DefaultTableModel modelo = (DefaultTableModel) tabla.getModel();
        modelo.setRowCount(0);
        for (Object[] fila : filas) modelo.addRow(fila);
    }

    private void cargarEventos() {
        if (!listo()) return;
        try { cargarTabla(JtblEventos, dao.eventosCliente()); }
        catch (Exception ex) { mostrarError("No se pudieron cargar los eventos", ex); }
    }

    private void cargarCuentas() {
        if (!listo()) return;
        try { cargarTabla(JtblMisCuentasCliente, dao.cuentasClienteTabla(session.idCliente())); }
        catch (Exception ex) { mostrarError("No se pudieron cargar las cuentas", ex); }
    }

    private void cargarHistorial() {
        if (!listo()) return;
        try { cargarTabla(JtblMisBoletos, dao.historialCompras(session.idCliente())); }
        catch (Exception ex) { mostrarError("No se pudo cargar el historial", ex); }
    }

    private void verEventoSeleccionado() {
        if (!listo()) return;
        int fila = JtblEventos.getSelectedRow();
        if (fila < 0) { JOptionPane.showMessageDialog(this, "Selecciona un evento."); return; }
        int m = JtblEventos.convertRowIndexToModel(fila);
        idEventoActual = ((Number) JtblEventos.getModel().getValueAt(m, 0)).intValue();
        nombreEventoActual = String.valueOf(JtblEventos.getModel().getValueAt(m, 1));
        JlblTextoNombreEvento.setText(nombreEventoActual);
        JlblTextoTipoEvento.setText(String.valueOf(JtblEventos.getModel().getValueAt(m, 2)));
        JlblTextoEdadMinEvento.setText(String.valueOf(JtblEventos.getModel().getValueAt(m, 3)));
        JlblTextoBoletosDisponibleEvento.setText(String.valueOf(JtblEventos.getModel().getValueAt(m, 4)));
        precioActual = new BigDecimal(String.valueOf(JtblEventos.getModel().getValueAt(m, 5)));
        JlblTextoPrecioBoleto.setText("$" + precioActual.setScale(2));
        promotoraActual = String.valueOf(JtblEventos.getModel().getValueAt(m, 6));
        JlblTextoNombrePromotora.setText(promotoraActual);
        try {
            EventData evento = dao.obtenerEvento(idEventoActual);
            cargarImagen(evento == null ? null : evento.imagenPromocion());
        } catch (Exception ex) {
            JlblImagenEvento.setIcon(null);
            JlblImagenEvento.setText("[Imagen no disponible]");
        }
        mostrarCard("card5");
    }

    private void cargarImagen(String ruta) {
        JlblImagenEvento.setIcon(null);
        if (ruta == null || ruta.isBlank()) { JlblImagenEvento.setText("[Sin imagen]"); return; }
        File archivo = new File(ruta);
        if (!archivo.exists()) archivo = new File("database", ruta);
        if (!archivo.exists()) { JlblImagenEvento.setText("[Imagen: " + ruta + "]"); return; }
        ImageIcon icon = new ImageIcon(archivo.getAbsolutePath());
        int w = Math.max(100, JlblImagenEvento.getWidth());
        int h = Math.max(100, JlblImagenEvento.getHeight());
        Image scaled = icon.getImage().getScaledInstance(w, h, Image.SCALE_SMOOTH);
        JlblImagenEvento.setText("");
        JlblImagenEvento.setIcon(new ImageIcon(scaled));
    }

    private void cargarBoletosDisponibles() {
        if (!listo() || idEventoActual == 0) return;
        try {
            List<ComboItem> boletos = dao.boletosDisponibles(idEventoActual);
            DefaultTableModel modelo = (DefaultTableModel) JtblSeleccionarBoletos.getModel();
            modelo.setRowCount(0);
            for (ComboItem b : boletos) modelo.addRow(new Object[]{b.id(), b.label(), precioActual.doubleValue(), "DISPONIBLE"});
            mostrarCard("card6");
        } catch (Exception ex) { mostrarError("No se pudieron cargar los boletos", ex); }
    }

    private void seleccionarBoleto() {
        int fila = JtblSeleccionarBoletos.getSelectedRow();
        if (fila < 0) { JOptionPane.showMessageDialog(this, "Selecciona un boleto."); return; }
        int m = JtblSeleccionarBoletos.convertRowIndexToModel(fila);
        idBoletoActual = ((Number) JtblSeleccionarBoletos.getModel().getValueAt(m, 0)).intValue();
        folioActual = String.valueOf(JtblSeleccionarBoletos.getModel().getValueAt(m, 1));
        try {
            cuentasClienteActuales = dao.cuentasClienteCombo(session.idCliente());
            JcmbCuentasCliente.removeAllItems();
            for (ComboItem c : cuentasClienteActuales) JcmbCuentasCliente.addItem(c.label());
            JtxtaResumenCompra.setText(
                    "Cliente: " + session.nombre() + "\n" +
                    "Evento: " + nombreEventoActual + "\n" +
                    "Boleto: " + folioActual + "\n" +
                    "Precio final: $" + precioActual.setScale(2) + "\n" +
                    "Promotora: " + promotoraActual + "\n\n" +
                    "Selecciona la cuenta con la que deseas pagar.");
            mostrarCard("card7");
        } catch (Exception ex) { mostrarError("No se pudieron cargar tus cuentas", ex); }
    }

    private void confirmarCompra() {
        if (JcmbCuentasCliente.getSelectedIndex() < 0 || cuentasClienteActuales.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecciona una cuenta para pagar."); return;
        }
        ComboItem cuenta = cuentasClienteActuales.get(JcmbCuentasCliente.getSelectedIndex());
        try {
            dao.comprarBoleto(session.idCliente(), idBoletoActual, cuenta.id(), precioActual);
            idCompraActual = dao.ultimaCompraIdCliente(session.idCliente());
            TicketPrintData t = dao.boletoParaImprimir(idCompraActual, session.idCliente());
            JtxtaResumenCompraExitosa.setText(resumenTicket(t));
            mostrarCard("card8");
            cargarEventos(); cargarHistorial(); cargarCuentas();
        } catch (Exception ex) { mostrarError("No se pudo realizar la compra", ex); }
    }

    private String resumenTicket(TicketPrintData t) {
        if (t == null) return "Compra registrada.";
        return "Código / folio: " + t.folio() + "\n" +
               "Evento: " + t.evento() + "\n" +
               "Precio: $" + t.precio().setScale(2) + "\n" +
               "Compra: " + t.idCompra() + "\n" +
               "Estado: " + t.estado() + "\n" +
               "Fecha: " + t.fechaCompra();
    }

    private void verPdfDesdeHistorial() {
        int fila = JtblMisBoletos.getSelectedRow();
        if (fila < 0) { JOptionPane.showMessageDialog(this, "Selecciona una compra."); return; }
        int m = JtblMisBoletos.convertRowIndexToModel(fila);
        int idCompra = ((Number) JtblMisBoletos.getModel().getValueAt(m, 0)).intValue();
        guardarPdf(idCompra);
    }

    private void guardarPdf(int idCompra) {
        if (!listo() || idCompra <= 0) return;
        try {
            TicketPrintData t = dao.boletoParaImprimir(idCompra, session.idCliente());
            if (t == null) { JOptionPane.showMessageDialog(this, "No se encontró el boleto."); return; }
            JFileChooser chooser = new JFileChooser();
            chooser.setSelectedFile(new File("boleto_" + t.folio().replaceAll("[^A-Za-z0-9_-]", "_") + ".pdf"));
            if (chooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) return;
            Path destino = chooser.getSelectedFile().toPath();
            pdfService.crearPdf(t, destino);
            JOptionPane.showMessageDialog(this, "PDF guardado en:\n" + destino.toAbsolutePath());
            if (Desktop.isDesktopSupported()) Desktop.getDesktop().open(destino.toFile());
        } catch (Exception ex) { mostrarError("No se pudo generar el PDF", ex); }
    }

    private void prepararCancelacion() {
        int fila = JtblMisBoletos.getSelectedRow();
        if (fila < 0) { JOptionPane.showMessageDialog(this, "Selecciona una compra."); return; }
        int m = JtblMisBoletos.convertRowIndexToModel(fila);
        String estado = String.valueOf(JtblMisBoletos.getModel().getValueAt(m, 5));
        if (!"COMPRADO".equalsIgnoreCase(estado)) { JOptionPane.showMessageDialog(this, "Esa compra ya no está activa."); return; }
        idCompraActual = ((Number) JtblMisBoletos.getModel().getValueAt(m, 0)).intValue();
        JtxtaCancelarCompra.setText(
                "Compra: " + idCompraActual + "\n" +
                "Evento: " + JtblMisBoletos.getModel().getValueAt(m, 1) + "\n" +
                "Boleto: " + JtblMisBoletos.getModel().getValueAt(m, 2) + "\n" +
                "Fecha: " + JtblMisBoletos.getModel().getValueAt(m, 3) + "\n" +
                "Reembolso: $" + JtblMisBoletos.getModel().getValueAt(m, 4) + "\n\n" +
                "La cancelación solo puede realizarse dentro de las primeras 24 horas.");
        mostrarCard("card9");
    }

    private void confirmarCancelacion() {
        if (idCompraActual <= 0) return;
        int r = JOptionPane.showConfirmDialog(this, "¿Confirmar cancelación y reembolso?", "Cancelar compra", JOptionPane.YES_NO_OPTION);
        if (r != JOptionPane.YES_OPTION) return;
        try {
            dao.cancelarCompra(idCompraActual);
            JOptionPane.showMessageDialog(this, "Compra cancelada y saldo reembolsado.");
            idCompraActual = 0;
            cargarHistorial(); cargarCuentas(); cargarEventos();
            mostrarCard("card4");
        } catch (Exception ex) { mostrarError("No se pudo cancelar la compra", ex); }
    }

    private void cerrarSesion() {
        new Login(dao).setVisible(true);
        dispose();
    }

    private void mostrarError(String mensaje, Exception ex) {
        JOptionPane.showMessageDialog(this, mensaje + ".\n" + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }


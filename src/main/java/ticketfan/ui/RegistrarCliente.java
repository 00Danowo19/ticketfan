    private void registrarCliente() {
        String nombres = JtxtNombres.getText().trim();
        String paterno = JtxtApellidoPaterno.getText().trim();
        String materno = JtxtApellidoMaterno.getText().trim();
        String fechaTexto = JtxtFechaNacimiento.getText().trim();
        String usuario = JtxtUsuario.getText().trim();
        String password = JtxtContraseña.getText();
        if (nombres.isEmpty() || paterno.isEmpty() || materno.isEmpty() || fechaTexto.isEmpty()
                || usuario.isEmpty() || password.isBlank()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            LocalDate fecha;
            try {
                fecha = LocalDate.parse(fechaTexto, DateTimeFormatter.ofPattern("yyyy/MM/dd"));
            } catch (DateTimeParseException ex) {
                fecha = LocalDate.parse(fechaTexto, DateTimeFormatter.ISO_LOCAL_DATE);
            }
            if (fecha.isAfter(LocalDate.now())) {
                JOptionPane.showMessageDialog(this, "La fecha de nacimiento no puede estar en el futuro.");
                return;
            }
            if (dao.usuarioClienteExiste(usuario)) {
                JOptionPane.showMessageDialog(this, "Ya existe un cliente con ese usuario.");
                return;
            }
            dao.registrarCliente(nombres, paterno, materno, Date.valueOf(fecha), usuario, password);
            JOptionPane.showMessageDialog(this, "Cliente registrado correctamente.\nSe crearon sus 3 cuentas automáticamente.");
            dispose();
        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Fecha inválida. Usa AAAA/MM/DD, por ejemplo 2003/05/10.");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el cliente.\n" + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }


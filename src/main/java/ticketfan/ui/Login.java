    private void configurarLogin() {
        setLocationRelativeTo(null);
        JpfContraseña.setText("");
        javax.swing.ButtonGroup grupo = new javax.swing.ButtonGroup();
        grupo.add(JrbCliente);
        grupo.add(JrbAdministrador);
        JrbCliente.setSelected(true);
        getRootPane().setDefaultButton(JbtnIniciarSesion);
    }

    private void iniciarSesion() {
        String usuario = JtxtUsuario.getText().trim();
        String password = new String(JpfContraseña.getPassword());
        if (usuario.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Captura usuario y contraseña.", "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            if (JrbAdministrador.isSelected()) {
                AdminSession s = dao.loginAdmin(usuario, password);
                if (s == null) {
                    JOptionPane.showMessageDialog(this, "Usuario o contraseña de administrador incorrectos.");
                    return;
                }
                new MenuAdministrador(s, dao).setVisible(true);
            } else {
                ClientSession s = dao.loginCliente(usuario, password);
                if (s == null) {
                    JOptionPane.showMessageDialog(this, "Usuario o contraseña de cliente incorrectos.");
                    return;
                }
                new MenuCliente(s, dao).setVisible(true);
            }
            dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "No se pudo iniciar sesión.\n" + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

